def render_pdf_preview_and_print(pdf_bytes: bytes):
    base64_pdf = base64.b64encode(pdf_bytes).decode("utf-8")

    print_html = f"""
    <!DOCTYPE html>
    <html>
    <head>
        <meta charset="utf-8">
        <style>
            .print-btn {{
                background-color: #ff4b4b;
                color: white;
                border: none;
                padding: 12px 24px;
                font-size: 16px;
                font-weight: bold;
                border-radius: 8px;
                cursor: pointer;
                box-shadow: 0 4px 6px rgba(0,0,0,0.1);
                width: 100%;
                text-align: center;
                font-family: sans-serif;
            }}
            .print-btn:hover {{
                background-color: #ff2222;
            }}
        </style>
    </head>
    <body>
        <button class="print-btn" onclick="openPrintWindow()">このまま印刷する</button>
        <script>
            function openPrintWindow() {{
                const pdfData = "{base64_pdf}";
                const byteCharacters = atob(pdfData);
                const byteNumbers = new Array(byteCharacters.length);
                for (let i = 0; i < byteCharacters.length; i++) {{
                    byteNumbers[i] = byteCharacters.charCodeAt(i);
                }}
                const byteArray = new Uint8Array(byteNumbers);
                const blob = new Blob([byteArray], {{type: 'application/pdf'}});
                const blobUrl = URL.createObjectURL(blob);
                const printWindow = window.open(blobUrl, '_blank');
                if (printWindow) {{
                    printWindow.onload = function() {{
                        printWindow.print();
                    }};
                }}
            }}
        </script>
    </body>
    </html>
    """

    st.markdown("### プレビュー & 印刷")
    components.html(print_html, height=65)
    st.markdown("---")

    try:
        doc = fitz.open(stream=pdf_bytes, filetype="pdf")
        for page_num in range(len(doc)):
            page = doc.load_page(page_num)
            pix = page.get_pixmap(dpi=150)
            img = Image.open(io.BytesIO(pix.tobytes("png")))

            st.image(
                img,
                caption=f"第 {page_num + 1} / {len(doc)} ページ",
                width=500,
            )
            if page_num < len(doc) - 1:
                st.markdown("---")
    except Exception as e:
        st.error(f"プレビューの生成に失敗しました: {e}")


